"""Build the «نبض بازار» (Market Pulse) page: live prices + economic calendar.

    python tools/market-pulse/build.py

Writes:
  market-pulse.html                 the page (static HTML, served at /market-pulse)
  assets/css/market-pulse.gen.css   calendar timeline positions (the CSP forbids
                                    inline style attributes, so geometry lives here)
and refreshes the /market-pulse <lastmod> in sitemap.xml.

The page chrome (head icons/fonts, nav, footer) is copied from about.html so
the header and footer always match the rest of the site.
"""
import hashlib
import html
import json
import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
import sys  # noqa: E402
sys.path.insert(0, str(Path(__file__).resolve().parent))
import cal  # noqa: E402  (economic calendar section + .ics)
HERE = Path(__file__).resolve().parent
SITE = 'https://bluepyramid.pages.dev'
FA_DIGITS = str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹')

e = html.escape


def fa(n):
    return str(n).translate(FA_DIGITS)


# ---------------------------------------------------------------- chrome
def chrome():
    about = (ROOT / 'about.html').read_text(encoding='utf-8')
    head = about[about.index('  <link rel="icon"'):about.index('  <script type="application/ld+json">')]
    top = about[about.index('<body>'):about.index('<main id="main">')]
    foot = about[about.index('<footer class="site-footer">'):about.index('<script type="application/json" id="i18n">')]
    top = top.replace(' aria-current="page" data-i18n="navAbout"', ' data-i18n="navAbout"')
    marker = '<a href="/market-pulse" class="nav-pulse" data-i18n="navPulse">'
    assert marker in top, 'nav link to /market-pulse missing in about.html'
    top = top.replace(marker, '<a href="/market-pulse" class="nav-pulse" aria-current="page" data-i18n="navPulse">')
    return head, top, foot


# ---------------------------------------------------------------- sections
def asset_card(asset, i):
    """A live price card; assets/js/market-pulse.js fills in the price."""
    return f'''        <article class="card asset asset--{asset["color"]}" data-reveal data-d="{i}" aria-labelledby="as-{asset["id"]}"
                 data-asset="{asset["id"]}" data-decimals="{asset.get("decimals", 0)}">
          <header class="asset__head">
            <h3 id="as-{asset["id"]}"><span class="asset__dot" aria-hidden="true"></span>{e(asset["name"])}</h3>
            <span class="asset__pair ltr">{e(asset["pair"])}</span>
          </header>
          <p class="asset__price ltr" data-live-price>—</p>
          <p class="asset__unit">دلار آمریکا · {e(asset["unit"])}</p>
          <p class="asset__note"><span data-live-note>در حال دریافت قیمت لحظه‌ای…</span></p>
        </article>'''


# ---------------------------------------------------------------- page
def build():
    data = json.loads((HERE / 'data.json').read_text(encoding='utf-8'))
    head_common, body_top, footer = chrome()
    css = ['/* generated by tools/market-pulse/build.py — do not edit */']
    calendar = cal.load()

    assets_html = '\n'.join(asset_card(a, i + 1) for i, a in enumerate(data['assets']))
    cal_html = cal.section(css)
    css_text = '\n'.join(css) + '\n'
    ver = hashlib.sha1(css_text.encode()).hexdigest()[:8]
    (ROOT / 'assets/css/market-pulse.gen.css').write_text(css_text, encoding='utf-8', newline='\n')

    title = 'نبض بازار | قیمت لحظه‌ای طلا، بیت‌کوین و اتریوم و تقویم اقتصادی — هرم آبی'
    desc = ('نبض بازار هرم آبی: قیمت لحظه‌ای طلا، بیت‌کوین و اتریوم و تقویم اقتصادی سه ماه آینده؛ '
            'جلسات فدرال رزرو و بانک مرکزی اروپا و انتشار CPI، اشتغال، GDP و PCE به وقت تهران.')
    lead = 'قیمت لحظه‌ای طلا، بیت‌کوین و اتریوم، همراه با تقویم جلسات و داده‌های اقتصادی مهم سه ماه آینده.'
    url = f'{SITE}/market-pulse'
    ld = {
        '@context': 'https://schema.org',
        '@graph': [
            {
                '@type': 'WebPage',
                '@id': f'{url}#webpage',
                'url': url,
                'name': 'نبض بازار — قیمت لحظه‌ای و تقویم اقتصادی',
                'description': desc,
                'inLanguage': 'fa-IR',
                'dateModified': calendar['updated'],
                'isPartOf': {'@id': f'{SITE}/#website'},
                'publisher': {'@id': f'{SITE}/#org'},
                'about': [{'@type': 'Thing', 'name': n} for n in ('طلا', 'بیت‌کوین', 'اتریوم', 'تقویم اقتصادی')],
            },
            {
                '@type': 'BreadcrumbList',
                'itemListElement': [
                    {'@type': 'ListItem', 'position': 1, 'name': 'خانه', 'item': f'{SITE}/'},
                    {'@type': 'ListItem', 'position': 2, 'name': 'نبض بازار', 'item': url},
                ],
            },
        ],
    }
    i18n = {'en': {
        'pageTitle': 'Market Pulse | Live gold, Bitcoin & Ethereum prices and economic calendar — Blue Pyramid',
        'crumbLabel': 'Breadcrumb',
        'phoneDisplay': '+98&nbsp;920&nbsp;741&nbsp;3175',
    }}

    page = f'''<!DOCTYPE html>
<html lang="fa" dir="rtl">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <title>{e(title)}</title>
  <meta name="description" content="{e(desc)}">
  <link rel="canonical" href="{url}">
  <meta name="robots" content="index, follow, max-image-preview:large">
  <meta name="theme-color" content="#030a16">
  <meta name="format-detection" content="telephone=no">
  <meta property="og:type" content="website">
  <meta property="og:site_name" content="Blue Pyramid — هرم آبی">
  <meta property="og:locale" content="fa_IR">
  <meta property="og:url" content="{url}">
  <meta property="og:title" content="نبض بازار — قیمت لحظه‌ای و تقویم اقتصادی">
  <meta property="og:description" content="{e(lead)}">
  <meta property="og:image" content="{SITE}/assets/img/og-image.jpg">
  <meta property="og:image:width" content="1200">
  <meta property="og:image:height" content="630">
  <meta name="twitter:card" content="summary_large_image">
  <meta name="twitter:image" content="{SITE}/assets/img/og-image.jpg">

{head_common}  <link rel="stylesheet" href="/assets/css/market-pulse.css?v=4.1">
  <link rel="stylesheet" href="/assets/css/market-pulse.gen.css?v={ver}">
  <script type="application/ld+json">
{json.dumps(ld, ensure_ascii=False, indent=2)}
  </script>
</head>
{body_top}<main id="main">
  <p class="lang-note container pulse-note">Market Pulse is published in Persian only.</p>
  <div class="pulse" lang="fa" dir="rtl">
  <section class="page-hero pulse-hero" aria-labelledby="page-title">
    <div class="container">
      <nav aria-label="مسیر صفحه">
        <ol class="breadcrumb">
          <li><a href="/">خانه</a></li>
          <li aria-current="page">نبض بازار</li>
        </ol>
      </nav>
      <p class="eyebrow" data-enter>Market Pulse</p>
      <p class="pulse-hero__kicker" data-enter data-d="1">قیمت لحظه‌ای و تقویم اقتصادی</p>
      <h1 id="page-title" data-enter="headline" data-d="2">نبض <span class="text-gradient">بازار</span></h1>
      <p class="pulse-hero__lead" data-enter data-d="3">{e(lead)}</p>
      <p class="live-status" data-live-status data-state="loading" role="status" data-enter data-d="4">در حال اتصال به قیمت لحظه‌ای…</p>
    </div>
  </section>

  <section class="section section--tight pulse-prices" aria-labelledby="prices-title">
    <div class="container">
      <div class="section-head pulse-head" data-reveal>
        <p class="eyebrow">Live Prices</p>
        <h2 class="section-title" id="prices-title">قیمت <span class="text-gradient">لحظه‌ای</span></h2>
      </div>
      <div class="assets-grid">
{assets_html}
      </div>
    </div>
  </section>

{cal_html}

  <section class="section section--tight pulse-notes" aria-label="منبع و توضیح">
    <div class="container">
      <div class="pulse-foot" data-reveal>
        <p class="pulse-foot__warn"><svg aria-hidden="true"><use href="/assets/img/icons.svg#i-shield"/></svg>{e(data["disclaimer"])}</p>
        <p class="pulse-foot__src">{e(data["source"])}</p>
      </div>
    </div>
  </section>

  <section class="section section--tight" aria-labelledby="cta-title">
    <div class="container">
      <div class="cta-band" data-reveal="scale">
        <h2 id="cta-title">برای تصمیم مالی کسب‌وکارتان <span class="text-gradient">مشاوره</span> می‌خواهید؟</h2>
        <p>در جلسه تشخیصی رایگان، وضعیت مالی و استراتژیک کسب‌وکار شما را با هم بررسی می‌کنیم.</p>
        <div class="cta-band__actions">
          <a class="btn btn--primary" href="/#contact" data-magnetic><span>رزرو جلسه رایگان</span><svg class="icon-arrow" aria-hidden="true"><use href="/assets/img/icons.svg#i-arrow"/></svg></a>
        </div>
      </div>
    </div>
  </section>
  </div>
</main>

{footer}<script type="application/json" id="i18n">
{json.dumps(i18n, ensure_ascii=False, indent=2)}
</script>
<script src="/assets/js/site.js?v=2.9" defer></script>
<script src="/assets/js/market-pulse.js?v=2.0" defer></script>
</body>
</html>
'''
    (ROOT / 'market-pulse.html').write_text(page, encoding='utf-8', newline='\n')

    # sitemap: keep the /market-pulse entry, with lastmod = last calendar change
    sm_path = ROOT / 'sitemap.xml'
    sm = sm_path.read_text(encoding='utf-8')
    entry = (f'  <url>\n    <loc>{url}</loc>\n    <lastmod>{calendar["updated"]}</lastmod>\n'
             f'    <changefreq>weekly</changefreq>\n    <priority>0.9</priority>\n  </url>\n')
    if f'<loc>{url}</loc>' in sm:
        sm = re.sub(rf'  <url>\n    <loc>{re.escape(url)}</loc>.*?</url>\n', entry, sm, flags=re.S)
    else:
        sm = sm.replace('</urlset>', entry + '</urlset>')
    sm_path.write_text(sm, encoding='utf-8', newline='\n')
    print(f'built market-pulse.html (calendar {calendar["from"]}..{calendar["to"]}, css v={ver})')


if __name__ == '__main__':
    build()
